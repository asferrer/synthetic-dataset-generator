"""Empirical statistics of the real data (training split) for profile v10.

The file is generated by scripts/build_real_stats.py from the real training COCO (never validation or test) and holds,
per class, quantiles of the square root of the relative box area and, globally, the histogram of objects per image.

Truncated size sampling: the target size is obtained by inverse transform. If the physical limits (object inside the
image, maximum crop upscaling, minimum size in pixels) cut the reachable range [lo, hi], the real distribution
CONDITIONED on that range is sampled (the quantile u is rescaled to the interval [F(lo), F(hi)]); values are not
piled up at the limit.
"""

import json
import os
from functools import lru_cache
from typing import Dict, List, Optional, Tuple

import numpy as np

DEFAULT_STATS_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "data", "real_stats_train.json"
)


class RealStats:
    """Per-class size quantiles and distribution of objects per image."""

    def __init__(self, data: dict):
        self.source = data.get("source", "")
        self._quantiles: Dict[str, np.ndarray] = {
            cls.lower(): np.asarray(v["sqrt_area_rel_quantiles"], dtype=np.float64)
            for cls, v in data.get("classes", {}).items()
        }
        hist = {int(k): int(v) for k, v in data.get("objects_per_image", {}).items()}
        self.image_sizes: Dict[Tuple[int, int], int] = {
            tuple(int(n) for n in k.split("x")): int(v)
            for k, v in data.get("image_sizes", {}).items()
        }
        image_stats = data.get("image_stats") or {}
        self.jpeg_quality_quantiles: List[float] = image_stats.get("jpeg_quality_quantiles", [])
        self.l_std_quantiles: List[float] = image_stats.get("l_std_quantiles", [])
        self._count_values = sorted(hist)
        self._count_weights = [hist[k] for k in self._count_values]

    @staticmethod
    def _interp(quantiles: List[float], u: float) -> float:
        return float(np.interp(u, np.linspace(0.0, 1.0, len(quantiles)), quantiles))

    def jpeg_quality(self, u: float) -> Optional[float]:
        """JPEG quality at quantile u of the sampled real images (None if unavailable)."""
        return self._interp(self.jpeg_quality_quantiles, u) if self.jpeg_quality_quantiles else None

    def l_std(self, u: float) -> Optional[float]:
        """Global contrast (std of L) at quantile u of the real images (None if unavailable)."""
        return self._interp(self.l_std_quantiles, u) if self.l_std_quantiles else None

    def has_class(self, class_name: str) -> bool:
        return class_name.lower() in self._quantiles

    def quantile(self, class_name: str, u: float) -> float:
        """Size (square root of the relative area) at quantile u of the class."""
        q = self._quantiles[class_name.lower()]
        return float(np.interp(u, np.linspace(0.0, 1.0, len(q)), q))

    def cdf(self, class_name: str, value: float) -> float:
        """Fraction of real objects of the class with size <= value."""
        q = self._quantiles[class_name.lower()]
        return float(np.interp(value, q, np.linspace(0.0, 1.0, len(q))))

    def truncated_size(
        self, class_name: str, u: float, lo: float, hi: float
    ) -> Tuple[float, bool]:
        """Size sampled from the real distribution conditioned on [lo, hi].

        Returns (size, truncated). If the class has no mass in [lo, hi]
        (the whole distribution lies outside) it returns the nearest limit.
        """
        q = self._quantiles[class_name.lower()]
        if hi <= q[0]:
            return float(hi), True
        if lo >= q[-1]:
            return float(lo), True
        f_lo, f_hi = self.cdf(class_name, lo), self.cdf(class_name, hi)
        if f_hi - f_lo < 1e-9:
            return float(min(max(self.quantile(class_name, f_lo), lo), hi)), True
        size = self.quantile(class_name, f_lo + u * (f_hi - f_lo))
        return float(min(max(size, lo), hi)), (f_lo > 0.0 or f_hi < 1.0)

    def count_distribution(self, cap: int) -> Tuple[List[int], List[int]]:
        """(values, weights) of the number of objects per image truncated to <= cap."""
        pairs = [(v, w) for v, w in zip(self._count_values, self._count_weights) if v <= cap]
        return [p[0] for p in pairs], [p[1] for p in pairs]

    def sample_count(self, rng, cap: int) -> int:
        """Number of objects in an image: real distribution conditioned on <= cap."""
        values, weights = self.count_distribution(cap)
        if not values:
            return 1
        return int(rng.choices(values, weights=weights, k=1)[0])


@lru_cache(maxsize=4)
def load_stats(path: Optional[str] = None) -> RealStats:
    """Loads (and caches) the statistics JSON; the bundled training-split one by default."""
    with open(path or DEFAULT_STATS_PATH, "r", encoding="utf-8") as f:
        return RealStats(json.load(f))
